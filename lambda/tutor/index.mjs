/**
 * "Ask the margin" lesson tutor — a response-streaming Lambda behind a Function
 * URL. It grounds a Claude answer in the single lesson the learner is reading,
 * refuses anything outside it, and never invents Braket/PennyLane APIs.
 *
 * PROVIDER, 2026-08-17: Anthropic's first-party Messages API, not Amazon
 * Bedrock. Bedrock never entitled this account to the paid models — sonnet-5,
 * opus-5 and fable-5 all answered `converse` with "not available for this
 * account ... contact AWS Sales", while `get-foundation-model-availability`
 * simultaneously reported them AUTHORIZED. Only haiku-4-5 was invocable, so
 * every tier above free was unreachable on the old provider.
 *
 * The prompt/grounding logic is imported from ./tutor-core.mjs (the single
 * source of truth, shared with web/src/lib/tutor.ts and the corpus builder).
 * corpus.json is generated by scripts/build_tutor_corpus.mjs.
 *
 * The per-request logic lives in `createHandlerCore` with its dependencies
 * (Anthropic client, corpus) injected, so it can be unit-tested
 * (lambda/tutor/index.test.mjs) without the Lambda runtime, a real model call,
 * or a packaged corpus. The production `handler` wires the real dependencies
 * through the `awslambda` streaming wrapper.
 *
 * `awslambda` is a global provided by the Lambda Node runtime when response
 * streaming is enabled (InvokeMode: RESPONSE_STREAM on the Function URL).
 */
